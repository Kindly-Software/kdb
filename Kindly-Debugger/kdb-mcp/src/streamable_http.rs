//! - Session state automatically cleaned on termination
//! - Stale sessions pruned by timeout
//! - Generation counter invalidates stale references
//!
//! ## MCP Streamable HTTP Protocol (2025-06-18)
//!
//! ### Endpoints
//! - `POST /mcp` - All MCP messages (requests, notifications, responses)
//! - `DELETE /mcp` - Session termination
//! - `GET /mcp` - SSE stream re-establishment (optional, with Last-Event-ID)
//!
//! ### Content Negotiation
//! - `Accept: application/json` → JSON response (200 + body)
//! - `Accept: text/event-stream` → SSE stream response (200 + streaming)
//! - Notification requests → 202 Accepted (no response needed)
//!
//! ### Headers (MCP-specific)
//! - `Mcp-Session-Id` - Session identifier (generated by server)
//! - `Mcp-Protocol-Version` - Protocol version (2025-06-18)
//! - `Last-Event-ID` - SSE resumption point
//! - `X-License-Key` / `Authorization` - API key authentication
//!
//! ## Memory Layout (768 bytes, 256-byte aligned)
//!
//! ```text
//! Cache Line 1 (64 bytes) - State:
//!   ├─ state (8 bytes):           Packed: state(8) + requests(24) + timestamp(32)
//!   ├─ generation (8 bytes):      TOCTOU prevention (AtomicU64)
//!   ├─ protocol_version (8 bytes): MCP spec version encoded (AtomicU64)
//!   └─ _state_reserved (40 bytes): Future expansion
