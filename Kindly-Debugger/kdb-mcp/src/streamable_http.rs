//!   ├─ json_responses (8 bytes):        Accept: application/json
//!   ├─ sse_streams (8 bytes):           Accept: text/event-stream
//!   ├─ notifications_accepted (8 bytes): 202 responses
//!   ├─ session_terminations (8 bytes):  DELETE /mcp count
//!   ├─ auth_bypassed (8 bytes):         Protocol methods
//!   ├─ errors (8 bytes):                Total errors
//!   └─ avg_latency_ns (8 bytes):        EMA latency
//!
//! Cache Lines 3-4 (128 bytes) - Session State:
//!   ├─ active_sessions (8 bytes):       AtomicU64
//!   ├─ max_sessions (8 bytes):          AtomicU64
//!   ├─ last_event_id_counter (8 bytes): AtomicU64
//!   ├─ session_timeouts (8 bytes):      AtomicU64
//!   └─ _session_reserved (96 bytes):    Future expansion
//!
//! Cache Line 5 (64 bytes) - Configuration:
//!   ├─ port (4 bytes):                  AtomicU32
//!   ├─ max_body_size (4 bytes):         AtomicU32
//!   ├─ request_timeout_ms (4 bytes):    AtomicU32
//!   ├─ flags (4 bytes):                 AtomicU32 (bit 0: cors, bit 1: streaming)
//!   └─ _config_reserved (48 bytes):     Future expansion
