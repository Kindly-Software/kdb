/// Transport lifecycle states
///
/// **Memory**: 1 byte (stored in packed AtomicU64)
/// **Valid Transitions**: STOPPED→STARTING→RUNNING→DRAINING→STOPPED
#[repr(u8)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TransportState {
    /// Transport is stopped
    Stopped = 0,
    /// Transport is starting up
    Starting = 1,
    /// Transport is running and accepting requests
    Running = 2,
    /// Transport is draining (rejecting new requests, processing existing)
    Draining = 3,
}

impl TransportState {
    /// Convert from u8 (for packed atomic storage)
    #[inline]
    pub const fn from_u8(value: u8) -> Option<Self> {
        match value {
            0 => Some(Self::Stopped),
            1 => Some(Self::Starting),
            2 => Some(Self::Running),
            3 => Some(Self::Draining),
            _ => None,
        }
    }

    /// Convert to u8 (for packed atomic storage)
    #[inline]
    pub const fn as_u8(self) -> u8 {
        self as u8
    }

    /// Check if transition is valid
    #[inline]
    pub const fn is_valid_transition(from: Self, to: Self) -> bool {
        matches!(
            (from, to),
            (Self::Stopped, Self::Starting)
                | (Self::Starting, Self::Running)
                | (Self::Starting, Self::Stopped) // Failed start
                | (Self::Running, Self::Draining)
                | (Self::Draining, Self::Stopped)
        )
    }
}

