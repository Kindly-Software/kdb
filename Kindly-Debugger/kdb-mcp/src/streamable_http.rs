/// MCP-specific headers parsed from request
///
/// Contains all headers relevant to MCP Streamable HTTP protocol.
#[derive(Debug, Clone, Default)]
pub struct McpHeaders {
    /// Mcp-Session-Id header (session identifier)
    pub session_id: Option<String>,
    /// Mcp-Protocol-Version header
    pub protocol_version: Option<String>,
    /// Last-Event-ID header (SSE resumption)
    pub last_event_id: Option<String>,
    /// X-License-Key or Authorization Bearer token
    pub api_key: Option<String>,
    /// Accept header (for content negotiation)
    pub accept: String,
    /// Content-Type header
    pub content_type: Option<String>,
}

impl McpHeaders {
    /// Create new McpHeaders with default Accept
    #[inline]
    pub fn new() -> Self {
        Self {
            accept: "application/json".to_string(),
            ..Default::default()
        }
    }

    /// Check if Accept header prefers SSE
    #[inline]
    pub fn prefers_sse(&self) -> bool {
        self.accept.contains("text/event-stream")
    }

    /// Check if Accept header prefers JSON
    #[inline]
    pub fn prefers_json(&self) -> bool {
        self.accept.contains("application/json") || self.accept.is_empty()
    }
}

