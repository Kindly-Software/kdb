///
/// **Tier**: T6 Mixed (T1+T5+T8)
/// **Size**: 768 bytes
/// **Alignment**: 256 bytes (cache-line aligned, prevents false sharing)
/// **Lockfree**: 100% (no mutex/RwLock)
///
/// # UCE35 Compliance
/// - Q10: T6 Mixed tier (T1 Atomic + T5 Streaming + T8 Network)
/// - Q33: 100% lockfree, AtomicU64/AtomicU32 only
/// - Q34: Generation counters, audit event tracking
/// - Q35: Session cleanup on termination
///
/// # ASSUM Safety Tags
/// - #ASSUME_LOCKFREE: All operations use atomic primitives
/// - #ASSUME_VALID_FSM: CAS enforces valid state transitions
/// - #ASSUME_GENERATION_COUNTER: Generation prevents TOCTOU races
/// - #ASSUME_CACHE_ALIGNED_256B: 256B alignment prevents false sharing
/// - #ASSUME_SESSION_ID_UNIQUE: Timestamp + generation ensures uniqueness
#[repr(C, align(256))]
pub struct StreamableHttpTransportCapsule {
    // ========================================================================
    // State (64 bytes - first cache line)
    // ========================================================================
    /// Packed state: state(8 bits) + requests(24 bits) + timestamp(32 bits)
    /// #ASSUME_VALID_FSM: CAS ensures valid transitions
    state: AtomicU64,

    /// Generation counter for TOCTOU prevention
    /// #ASSUME_GENERATION_COUNTER: Incremented on every state change
    generation: AtomicU64,

    /// MCP protocol version (2025-06-18 encoded as YYYYMMDD)
    protocol_version: AtomicU64,

    /// Reserved for future state expansion
    _state_reserved: [u64; 5],

    // ========================================================================
    // Metrics (64 bytes - second cache line)
    // ========================================================================
    /// Total requests processed (lifetime)
    total_requests: AtomicU64,

    /// JSON responses (Accept: application/json)
    json_responses: AtomicU64,

    /// SSE streams opened (Accept: text/event-stream)
    sse_streams: AtomicU64,

    /// Notifications accepted (202 responses)
    notifications_accepted: AtomicU64,

    /// Session terminations (DELETE /mcp)
    session_terminations: AtomicU64,

    /// Auth bypassed count (protocol methods)
    auth_bypassed: AtomicU64,

    /// Total errors encountered
    errors: AtomicU64,

    /// Average latency (nanoseconds, EMA)
    avg_latency_ns: AtomicU64,

    // ========================================================================
    // Session State (128 bytes - third/fourth cache lines)
    // ========================================================================
    /// Currently active sessions
    active_sessions: AtomicU64,

    /// Maximum concurrent sessions allowed
    max_sessions: AtomicU64,

    /// Last-Event-ID counter for SSE resumption
    last_event_id_counter: AtomicU64,

    /// Session timeout count
    session_timeouts: AtomicU64,

    /// Reserved for session expansion
    _session_reserved: [u64; 12],

    // ========================================================================
    // Configuration (64 bytes - fifth cache line)
    // ========================================================================
    /// Port number
    port: AtomicU32,

    /// Maximum request body size (bytes)
    max_body_size: AtomicU32,

    /// Request timeout (milliseconds)
    request_timeout_ms: AtomicU32,

    /// Flags: bit 0 = cors_enabled, bit 1 = streaming_enabled
    flags: AtomicU32,

    /// Reserved for configuration expansion
    _config_reserved: [u64; 6],

    // ========================================================================
    // Reserved (448 bytes for future expansion)
    // ========================================================================
    _reserved: [u64; 56],
}

