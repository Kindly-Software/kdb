/// MCP response variants
#[derive(Debug, Clone)]
pub enum McpResponse {
    /// JSON response (200 + body)
    Json {
        status: u16,
        body: String,
        session_id: Option<String>,
    },
    /// SSE stream established
    SseStream { session_id: String },
    /// 202 Accepted (notification)
    Accepted { session_id: String },
    /// Error response
    Error {
        status: u16,
        code: i32,
        message: String,
    },
}

impl McpResponse {
    /// Create JSON response
    #[inline]
    pub fn json(body: String, session_id: Option<String>) -> Self {
        Self::Json {
            status: 200,
            body,
            session_id,
        }
    }

    /// Create error response from StreamableHttpError
    #[inline]
    pub fn from_error(error: StreamableHttpError) -> Self {
        Self::Error {
            status: error.http_status(),
            code: error.json_rpc_code(),
            message: error.to_string(),
        }
    }

    /// Format as JSON-RPC error response
    pub fn to_json_rpc_error(&self, id: Option<u64>) -> String {
        match self {
            Self::Error { code, message, .. } => {
                let id_str = id.map(|i| i.to_string()).unwrap_or_else(|| "0".to_string());
                format!(
                    r#"{{"jsonrpc":"2.0","error":{{"code":{},"message":"{}"}},"id":{}}}"#,
                    code, message, id_str
                )
            }
            _ => String::new(),
        }
    }
}

