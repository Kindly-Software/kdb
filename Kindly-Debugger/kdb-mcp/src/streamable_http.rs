/// Response type from content negotiation
///
/// Determined by Accept header and request body (notification vs request).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ResponseType {
    /// 200 + application/json (synchronous response)
    Json,
    /// 200 + text/event-stream (SSE streaming)
    Sse,
    /// 202 Accepted (notification, no response body)
    Accepted,
}

impl ResponseType {
    /// Get HTTP Content-Type for this response type
    #[inline]
    pub const fn content_type(&self) -> &'static str {
        match self {
            Self::Json => "application/json",
            Self::Sse => "text/event-stream",
            Self::Accepted => "", // No body
        }
    }

    /// Get HTTP status code for this response type
    #[inline]
    pub const fn status_code(&self) -> u16 {
        match self {
            Self::Json => 200,
            Self::Sse => 200,
            Self::Accepted => 202,
        }
    }
}

