/// Async HTTP client for KindlyDB
///
/// Provides user storage and Q34-compliant audit logging.
///
/// # Connection
///
/// Connects to KindlyDB at the URL specified by `KINDLYDB_URL` environment
/// variable, or manually via `KindlyDbClient::new()`.
///
/// # Endpoints
///
/// - `POST /users` - Create user
/// - `GET /users?email_hash={hash}` - Find by email hash
/// - `GET /users/{id}` - Get by ID
/// - `PUT /users/{id}` - Update user
/// - `POST /audit` - Log audit entry
/// - `GET /audit?user_id={id}` - Get audit trail
#[derive(Clone)]
pub struct KindlyDbClient {
    base_url: String,
    client: reqwest::Client,
}

impl KindlyDbClient {
    /// Create a new KindlyDB client with explicit URL
    ///
    /// # Arguments
    ///
    /// * `base_url` - KindlyDB base URL (e.g., "http://kindly-hub:8080")
    pub fn new(base_url: &str) -> Self {
        Self {
            base_url: base_url.trim_end_matches('/').to_string(),
            client: reqwest::Client::new(),
        }
    }

    /// Create client from KINDLYDB_URL environment variable
    ///
    /// # Errors
    ///
    /// Returns `DbError::MissingUrl` if KINDLYDB_URL is not set.
    pub fn from_env() -> Result<Self, DbError> {
        let url = env::var("KINDLYDB_URL").map_err(|_| DbError::MissingUrl)?;
        Ok(Self::new(&url))
    }

    // ========================================================================
    // User Operations
    // ========================================================================

    /// Create a new user
    ///
    /// # Arguments
    ///
    /// * `user` - User data (id field is ignored, assigned by server)
    ///
    /// # Returns
    ///
    /// The assigned user ID.
    ///
    /// # Errors
    ///
    /// - `DbError::AlreadyExists` if email_hash already exists
    /// - `DbError::ConnectionFailed` on network error
    pub async fn create_user(&self, user: &User) -> Result<u64, DbError> {
        let url = format!("{}/users", self.base_url);

        let response = self.client.post(&url).json(user).send().await?;

        match response.status().as_u16() {
            200 | 201 => {
                let result: CreateUserResponse = response.json().await?;
                Ok(result.id)
            }
            409 => Err(DbError::AlreadyExists),
            status => Err(DbError::DatabaseError(format!(
                "Unexpected status {}: {}",
                status,
                response.text().await.unwrap_or_default()
            ))),
        }
    }

    /// Find user by email hash
    ///
    /// # Arguments
    ///
    /// * `email_hash` - BLAKE3 hash of email address
    ///
    /// # Returns
    ///
    /// `Some(User)` if found, `None` if not.
    pub async fn get_user_by_email_hash(&self, email_hash: u64) -> Result<Option<User>, DbError> {
        let url = format!("{}/users?email_hash={}", self.base_url, email_hash);

        let response = self.client.get(&url).send().await?;

        match response.status().as_u16() {
            200 => {
                let user: User = response.json().await?;
                Ok(Some(user))
            }
            404 => Ok(None),
            status => Err(DbError::DatabaseError(format!(
                "Unexpected status {}: {}",
                status,
                response.text().await.unwrap_or_default()
            ))),
        }
    }

    /// Get user by ID
    ///
    /// # Arguments
    ///
    /// * `id` - User ID
    ///
    /// # Returns
    ///
    /// `Some(User)` if found, `None` if not.
    pub async fn get_user_by_id(&self, id: u64) -> Result<Option<User>, DbError> {
        let url = format!("{}/users/{}", self.base_url, id);

        let response = self.client.get(&url).send().await?;

        match response.status().as_u16() {
            200 => {
                let user: User = response.json().await?;
                Ok(Some(user))
            }
            404 => Ok(None),
            status => Err(DbError::DatabaseError(format!(
                "Unexpected status {}: {}",
                status,
                response.text().await.unwrap_or_default()
            ))),
        }
    }

    /// Update an existing user
    ///
    /// # Arguments
    ///
    /// * `user` - Complete user data (must include valid id)
    ///
    /// # Errors
    ///
    /// - `DbError::NotFound` if user doesn't exist
    pub async fn update_user(&self, user: &User) -> Result<(), DbError> {
        let url = format!("{}/users/{}", self.base_url, user.id);

        let response = self.client.put(&url).json(user).send().await?;

        match response.status().as_u16() {
            200 | 204 => Ok(()),
            404 => Err(DbError::NotFound),
            status => Err(DbError::DatabaseError(format!(
                "Unexpected status {}: {}",
                status,
                response.text().await.unwrap_or_default()
            ))),
        }
    }

    /// Mark user as verified and issue license
    ///
    /// Convenience method that updates verification status,
    /// clears the token, and sets the license key.
    ///
    /// # Arguments
    ///
    /// * `user_id` - User ID
    /// * `license_key` - Generated license key
    /// * `is_promo` - Whether issued during promotional period
    pub async fn set_verified(
        &self,
        user_id: u64,
        license_key: &str,
        is_promo: bool,
    ) -> Result<(), DbError> {
        // Get current user
        let mut user = self
            .get_user_by_id(user_id)
            .await?
            .ok_or(DbError::NotFound)?;

        // Update verification fields
        user.email_verified = true;
        user.verification_token = None;
        user.verification_expires_at = None;
        user.license_key = Some(license_key.to_string());
        user.is_promo = is_promo;
        user.updated_at = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap_or_default()
            .as_secs();

        self.update_user(&user).await
    }

    // ========================================================================
    // Audit Operations (Q34 Compliance)
    // ========================================================================

    /// Log an audit entry
    ///
    /// The entry's `prev_hash` should be computed using `compute_audit_hash`
    /// with the previous entry's hash (or 0 for the first entry).
    ///
    /// # Arguments
    ///
    /// * `entry` - Audit entry (id field is ignored, assigned by server)
    pub async fn log_audit(&self, entry: &SignupAuditEntry) -> Result<(), DbError> {
        let url = format!("{}/audit", self.base_url);

        let response = self.client.post(&url).json(entry).send().await?;

        match response.status().as_u16() {
            200 | 201 => Ok(()),
            status => Err(DbError::DatabaseError(format!(
                "Unexpected status {}: {}",
                status,
                response.text().await.unwrap_or_default()
            ))),
        }
    }

    /// Get audit trail for a user
    ///
    /// Returns all audit entries in chronological order.
    ///
    /// # Arguments
    ///
    /// * `user_id` - User ID to get audit trail for
    pub async fn get_audit_trail(&self, user_id: u64) -> Result<Vec<SignupAuditEntry>, DbError> {
        let url = format!("{}/audit?user_id={}", self.base_url, user_id);

        let response = self.client.get(&url).send().await?;

        match response.status().as_u16() {
            200 => {
                let entries: Vec<SignupAuditEntry> = response.json().await?;
                Ok(entries)
            }
            status => Err(DbError::DatabaseError(format!(
                "Unexpected status {}: {}",
                status,
                response.text().await.unwrap_or_default()
            ))),
        }
    }
}

