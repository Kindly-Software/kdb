/// In-memory mock storage for testing
struct MockStorage {
    users: HashMap<u64, User>,
    users_by_email_hash: HashMap<u64, u64>,
    audit_entries: Vec<SignupAuditEntry>,
    next_user_id: AtomicU64,
    next_audit_id: AtomicU64,
}

impl MockStorage {
    fn new() -> Self {
        Self {
            users: HashMap::new(),
            users_by_email_hash: HashMap::new(),
            audit_entries: Vec::new(),
            next_user_id: AtomicU64::new(1),
            next_audit_id: AtomicU64::new(1),
        }
    }
}

/// Mock KindlyDB client for testing
///
/// Stores all data in memory, no network calls.
/// Thread-safe for concurrent test execution.
#[derive(Clone)]
pub struct MockKindlyDbClient {
    storage: Arc<RwLock<MockStorage>>,
}

impl MockKindlyDbClient {
    /// Create a new mock client
    pub fn new() -> Self {
        Self {
            storage: Arc::new(RwLock::new(MockStorage::new())),
        }
    }

    /// Create a user in mock storage
    pub async fn create_user(&self, user: &User) -> Result<u64, DbError> {
        let mut storage = self.storage.write().await;

        // Check for duplicate email_hash
        if storage.users_by_email_hash.contains_key(&user.email_hash) {
            return Err(DbError::AlreadyExists);
        }

        // Assign ID
        let id = storage.next_user_id.fetch_add(1, Ordering::SeqCst);
        let mut user = user.clone();
        user.id = id;

        // Store
        storage.users_by_email_hash.insert(user.email_hash, id);
        storage.users.insert(id, user);

        Ok(id)
    }

    /// Find user by email hash in mock storage
    pub async fn get_user_by_email_hash(&self, email_hash: u64) -> Result<Option<User>, DbError> {
        let storage = self.storage.read().await;

        match storage.users_by_email_hash.get(&email_hash) {
            Some(&id) => Ok(storage.users.get(&id).cloned()),
            None => Ok(None),
        }
    }

    /// Get user by ID from mock storage
    pub async fn get_user_by_id(&self, id: u64) -> Result<Option<User>, DbError> {
        let storage = self.storage.read().await;
        Ok(storage.users.get(&id).cloned())
    }

    /// Update user in mock storage
    pub async fn update_user(&self, user: &User) -> Result<(), DbError> {
        let mut storage = self.storage.write().await;

        if !storage.users.contains_key(&user.id) {
            return Err(DbError::NotFound);
        }

        storage.users.insert(user.id, user.clone());
        Ok(())
    }

    /// Mark user as verified in mock storage
    pub async fn set_verified(
        &self,
        user_id: u64,
        license_key: &str,
        is_promo: bool,
    ) -> Result<(), DbError> {
        let mut storage = self.storage.write().await;

        let user = storage.users.get_mut(&user_id).ok_or(DbError::NotFound)?;

        user.email_verified = true;
        user.verification_token = None;
        user.verification_expires_at = None;
        user.license_key = Some(license_key.to_string());
        user.is_promo = is_promo;
        user.updated_at = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap_or_default()
            .as_secs();

        Ok(())
    }

    /// Log audit entry in mock storage
    pub async fn log_audit(&self, entry: &SignupAuditEntry) -> Result<(), DbError> {
        let mut storage = self.storage.write().await;

        let id = storage.next_audit_id.fetch_add(1, Ordering::SeqCst);
        let mut entry = entry.clone();
        entry.id = id;

        storage.audit_entries.push(entry);
        Ok(())
    }

    /// Get audit trail from mock storage
    pub async fn get_audit_trail(&self, user_id: u64) -> Result<Vec<SignupAuditEntry>, DbError> {
        let storage = self.storage.read().await;

        let entries: Vec<SignupAuditEntry> = storage
            .audit_entries
            .iter()
            .filter(|e| e.user_id == user_id)
            .cloned()
            .collect();

        Ok(entries)
    }

    /// Get all users (test helper)
    pub async fn get_all_users(&self) -> Vec<User> {
        let storage = self.storage.read().await;
        storage.users.values().cloned().collect()
    }

    /// Get all audit entries (test helper)
    pub async fn get_all_audit_entries(&self) -> Vec<SignupAuditEntry> {
        let storage = self.storage.read().await;
        storage.audit_entries.clone()
    }

    /// Clear all data (test helper)
    pub async fn clear(&self) {
        let mut storage = self.storage.write().await;
        storage.users.clear();
        storage.users_by_email_hash.clear();
        storage.audit_entries.clear();
        storage.next_user_id = AtomicU64::new(1);
        storage.next_audit_id = AtomicU64::new(1);
    }
}

impl Default for MockKindlyDbClient {
    fn default() -> Self {
        Self::new()
    }
}

