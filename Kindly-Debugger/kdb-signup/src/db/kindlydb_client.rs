//! KindlyDB Client - Async HTTP client for KindlyDB user storage
//!
//! Connects to KindlyDB at kindly-hub:8080 for user and audit storage.
//!
//! # Q34 Audit Compliance
//!
//! All audit entries are hash-chained using BLAKE3 for tamper detection.
//! The `prev_hash` field links each entry to the previous one, creating
//! an immutable audit trail.
//!
//! # Example
//!
//! ```rust,ignore
//! use kdb_signup::db::KindlyDbClient;
//!
//! let client = KindlyDbClient::from_env()?;
//! let user = client.get_user_by_email_hash(email_hash).await?;
//! ```

use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::env;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;
use thiserror::Error;
use tokio::sync::RwLock;

// ============================================================================
// Error Types
// ============================================================================

/// Database operation errors
#[derive(Debug, Error)]
pub enum DbError {
    /// Connection to KindlyDB failed
    #[error("Connection failed: {0}")]
    ConnectionFailed(String),

    /// User not found
    #[error("User not found")]
    NotFound,

    /// User already exists (duplicate email_hash)
    #[error("User already exists")]
    AlreadyExists,

    /// Generic database error
    #[error("Database error: {0}")]
    DatabaseError(String),

    /// Missing KINDLYDB_URL environment variable
    #[error("Missing KINDLYDB_URL environment variable")]
    MissingUrl,
}

impl From<reqwest::Error> for DbError {
    fn from(err: reqwest::Error) -> Self {
        DbError::ConnectionFailed(err.to_string())
    }
}

// ============================================================================
// Data Structures
// ============================================================================

/// User record stored in KindlyDB
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct User {
    /// Unique user ID (auto-generated by KindlyDB)
    pub id: u64,

    /// BLAKE3 hash of email (indexed for fast lookup)
    pub email_hash: u64,

    /// Encrypted email for sending verification/license emails
    pub email_encrypted: String,

    /// Whether email has been verified
    pub email_verified: bool,

    /// Verification token (6-digit code)
    pub verification_token: Option<String>,

    /// Token expiration timestamp (Unix epoch seconds)
    pub verification_expires_at: Option<u64>,

    /// User tier: 0=Hobby, 1=Pro, 2=Enterprise
    pub tier: u8,

    /// License key (issued after verification)
    pub license_key: Option<String>,

    /// Organization name
    pub org_name: String,

    /// Whether license was issued during promotional period
    pub is_promo: bool,

    /// Creation timestamp (Unix epoch seconds)
    pub created_at: u64,

    /// Last update timestamp (Unix epoch seconds)
    pub updated_at: u64,
}

/// Audit entry for Q34 compliance
///
/// Each entry is hash-chained to the previous via `prev_hash`,
/// creating a tamper-evident audit trail.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SignupAuditEntry {
    /// Unique entry ID
    pub id: u64,

    /// Associated user ID
    pub user_id: u64,

    /// Event type: SIGNUP, VERIFIED, LICENSE_ISSUED, RESEND
    pub event_type: String,

    /// Client IP address
    pub ip_address: String,

    /// BLAKE3 hash linking to previous entry (Q34 chain)
    pub prev_hash: u64,

    /// Event timestamp (Unix epoch seconds)
    pub timestamp: u64,
}

/// Response from create user endpoint
#[derive(Debug, Deserialize)]
struct CreateUserResponse {
    id: u64,
}

// ============================================================================
// Hash Chain (Q34 Compliance)
// ============================================================================

/// Compute BLAKE3 hash for audit chain integrity
///
/// The hash includes all entry fields plus the previous hash,
/// creating an immutable chain that detects any tampering.
pub fn compute_audit_hash(entry: &SignupAuditEntry, prev_hash: u64) -> u64 {
    let data = format!(
        "{}:{}:{}:{}:{}",
        entry.user_id, entry.event_type, entry.ip_address, entry.timestamp, prev_hash
    );
    let hash = blake3::hash(data.as_bytes());
    u64::from_le_bytes(
        hash.as_bytes()[..8]
            .try_into()
            .expect("BLAKE3 always produces 32 bytes"),
    )
}

