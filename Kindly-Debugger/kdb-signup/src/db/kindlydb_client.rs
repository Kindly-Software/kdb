#[cfg(test)]
mod tests {
    use super::*;

    fn create_test_user() -> User {
        User {
            id: 0,
            email_hash: 12345678901234567890,
            email_encrypted: "encrypted_email_data".to_string(),
            email_verified: false,
            verification_token: Some("123456".to_string()),
            verification_expires_at: Some(1700000000),
            tier: 0,
            license_key: None,
            org_name: "Test Org".to_string(),
            is_promo: false,
            created_at: 1699999000,
            updated_at: 1699999000,
        }
    }

    #[tokio::test]
    async fn test_mock_create_user() {
        let client = MockKindlyDbClient::new();
        let user = create_test_user();

        let id = client.create_user(&user).await.unwrap();
        assert_eq!(id, 1);

        // Verify stored
        let stored = client.get_user_by_id(id).await.unwrap().unwrap();
        assert_eq!(stored.email_hash, user.email_hash);
        assert_eq!(stored.org_name, "Test Org");
    }

    #[tokio::test]
    async fn test_mock_duplicate_email_hash() {
        let client = MockKindlyDbClient::new();
        let user = create_test_user();

        client.create_user(&user).await.unwrap();

        // Try to create another with same email_hash
        let result = client.create_user(&user).await;
        assert!(matches!(result, Err(DbError::AlreadyExists)));
    }

    #[tokio::test]
    async fn test_mock_get_by_email_hash() {
        let client = MockKindlyDbClient::new();
        let user = create_test_user();

        let id = client.create_user(&user).await.unwrap();

        let found = client
            .get_user_by_email_hash(user.email_hash)
            .await
            .unwrap();
        assert!(found.is_some());
        assert_eq!(found.unwrap().id, id);

        // Non-existent hash
        let not_found = client.get_user_by_email_hash(9999999999).await.unwrap();
        assert!(not_found.is_none());
    }

    #[tokio::test]
    async fn test_mock_update_user() {
        let client = MockKindlyDbClient::new();
        let user = create_test_user();

        let id = client.create_user(&user).await.unwrap();

        // Update
        let mut updated = client.get_user_by_id(id).await.unwrap().unwrap();
        updated.org_name = "Updated Org".to_string();
        client.update_user(&updated).await.unwrap();

        // Verify
        let fetched = client.get_user_by_id(id).await.unwrap().unwrap();
        assert_eq!(fetched.org_name, "Updated Org");
    }

    #[tokio::test]
    async fn test_mock_update_nonexistent() {
        let client = MockKindlyDbClient::new();
        let mut user = create_test_user();
        user.id = 999;

        let result = client.update_user(&user).await;
        assert!(matches!(result, Err(DbError::NotFound)));
    }

    #[tokio::test]
    async fn test_mock_set_verified() {
        let client = MockKindlyDbClient::new();
        let user = create_test_user();

        let id = client.create_user(&user).await.unwrap();

        client
            .set_verified(id, "KDB-HOBBY-ABCD1234", true)
            .await
            .unwrap();

        let verified = client.get_user_by_id(id).await.unwrap().unwrap();
        assert!(verified.email_verified);
        assert!(verified.verification_token.is_none());
        assert_eq!(verified.license_key, Some("KDB-HOBBY-ABCD1234".to_string()));
        assert!(verified.is_promo);
    }

    #[tokio::test]
    async fn test_mock_audit_logging() {
        let client = MockKindlyDbClient::new();

        let entry = SignupAuditEntry {
            id: 0,
            user_id: 1,
            event_type: "SIGNUP".to_string(),
            ip_address: "192.168.1.1".to_string(),
            prev_hash: 0,
            timestamp: 1699999000,
        };

        client.log_audit(&entry).await.unwrap();

        let trail = client.get_audit_trail(1).await.unwrap();
        assert_eq!(trail.len(), 1);
        assert_eq!(trail[0].event_type, "SIGNUP");
    }

    #[tokio::test]
    async fn test_mock_audit_chain() {
        let client = MockKindlyDbClient::new();

        // First entry
        let entry1 = SignupAuditEntry {
            id: 0,
            user_id: 1,
            event_type: "SIGNUP".to_string(),
            ip_address: "192.168.1.1".to_string(),
            prev_hash: 0,
            timestamp: 1699999000,
        };

        let hash1 = compute_audit_hash(&entry1, 0);
        client.log_audit(&entry1).await.unwrap();

        // Second entry linked to first
        let entry2 = SignupAuditEntry {
            id: 0,
            user_id: 1,
            event_type: "VERIFIED".to_string(),
            ip_address: "192.168.1.1".to_string(),
            prev_hash: hash1,
            timestamp: 1699999100,
        };

        client.log_audit(&entry2).await.unwrap();

        let trail = client.get_audit_trail(1).await.unwrap();
        assert_eq!(trail.len(), 2);
        assert_eq!(trail[0].event_type, "SIGNUP");
        assert_eq!(trail[1].event_type, "VERIFIED");
        assert_eq!(trail[1].prev_hash, hash1);
    }

    #[tokio::test]
    async fn test_compute_audit_hash_deterministic() {
        let entry = SignupAuditEntry {
            id: 1,
            user_id: 42,
            event_type: "SIGNUP".to_string(),
            ip_address: "10.0.0.1".to_string(),
            prev_hash: 0,
            timestamp: 1699999999,
        };

        let hash1 = compute_audit_hash(&entry, 0);
        let hash2 = compute_audit_hash(&entry, 0);

        assert_eq!(hash1, hash2);

        // Different prev_hash produces different result
        let hash3 = compute_audit_hash(&entry, 12345);
        assert_ne!(hash1, hash3);
    }

    #[tokio::test]
    async fn test_mock_clear() {
        let client = MockKindlyDbClient::new();
        let user = create_test_user();

        client.create_user(&user).await.unwrap();
        assert_eq!(client.get_all_users().await.len(), 1);

        client.clear().await;
        assert_eq!(client.get_all_users().await.len(), 0);
    }
}
